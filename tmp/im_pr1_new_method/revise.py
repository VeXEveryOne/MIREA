def format_table(tbl,widths):
 for col,w in zip(tbl.columns,widths):col.width=Cm(w)
 for i,row in enumerate(tbl.rows):
  pr=row._tr.get_or_add_trPr()
  for x in list(pr.findall(qn('w:trHeight'))):pr.remove(x)
  if pr.find(qn('w:cantSplit')) is None:pr.append(OxmlElement('w:cantSplit'))
  if i==0 and pr.find(qn('w:tblHeader')) is None:pr.append(OxmlElement('w:tblHeader'))
  for j,(c,w) in enumerate(zip(row.cells,widths)):
   c.width=Cm(w);c.vertical_alignment=WD_ALIGN_VERTICAL.CENTER
   cp=c._tc.get_or_add_tcPr()
   for name in ['tcBorders','tcMar','shd']:
    for x in list(cp.findall(qn('w:'+name))):cp.remove(x)
   edges=OxmlElement('w:tcBorders');cp.append(edges)
   for side in ['top','left','bottom','right']:
    x=OxmlElement('w:'+side);x.set(qn('w:val'),'single');x.set(qn('w:sz'),'8');x.set(qn('w:color'),'D9D9D9');edges.append(x)
   mar=OxmlElement('w:tcMar');cp.append(mar)
   for side,num in [('top',80),('bottom',80),('start',100),('end',100)]:
    x=OxmlElement('w:'+side);x.set(qn('w:w'),str(num));x.set(qn('w:type'),'dxa');mar.append(x)
   if i==0:
    x=OxmlElement('w:shd');x.set(qn('w:fill'),'E7E6E6');cp.append(x)
   for p in c.paragraphs:
    p.style='Текст таблицы'
    pf=p.paragraph_format;pf.left_indent=Cm(0);pf.right_indent=Cm(0);pf.first_line_indent=Cm(0);pf.line_spacing=1;pf.space_before=Pt(0);pf.space_after=Pt(0);pf.keep_with_next=False
    p.alignment=WD_ALIGN_PARAGRAPH.CENTER if len(widths)==4 and j==0 else WD_ALIGN_PARAGRAPH.LEFT
    for r in p.runs:
     r.font.name='Times New Roman';r.font.size=Pt(12);r.bold=i==0;r.italic=False;r.font.color.rgb=RGBColor(0,0,0)
