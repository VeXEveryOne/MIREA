CLIENT = SUBJECT / 'Клиент'
SCHEMES = SUBJECT / 'Схемы'
PROOF = CLIENT / 'Результаты_проверки.json'
MODELS = SCHEMES / 'ПР10_Модели.json'


def digest(path):
    return sha256(Path(path).read_bytes()).hexdigest()


def inputs():
    contract = json.loads((CLIENT / 'client_contract.json').read_text(encoding='utf-8'))
    proof = json.loads(PROOF.read_text(encoding='utf-8'))
    models = json.loads(MODELS.read_text(encoding='utf-8'))
    if not proof['passed'] or (proof['http_tests'], proof['browser_checkpoints'], proof['reconciliation_checks']) != (28, 18, 111):
        raise ValueError('Complete HTTP/browser/SQL reconciliation required')
    for name, expected in proof['source_sha256'].items():
        if digest(CLIENT / name) != expected:
            raise ValueError('Stale client evidence: ' + name)
    for name, expected in proof['dependency_sha256'].items():
        if digest(SUBJECT / name) != expected:
            raise ValueError('Stale client dependency: ' + name)
    for name, expected in proof['evidence_sha256'].items():
        if digest(ROOT / '.cache/ppois5-10' / name) != expected:
            raise ValueError('Stale raw observation: ' + name)
    if digest(Path(__file__).with_name('verify_client_10.py')) != proof['verifier_sha256']:
        raise ValueError('Client verifier changed')
    if models['diagnostics'] or not models['semantic_round_trip']:
        raise ValueError('Native models not verified')
    for path, expected in ((SCHEMES / models['native_file'], models['native_sha256']),
                           (CLIENT / 'client_contract.json', models['contract_sha256']),
                           (Path(__file__).with_name('build_client_models.mts'), models['source_sha256'])):
        if digest(path) != expected:
            raise ValueError('Stale native model ' + path.name)
    for image in models['emitted'] + proof['screenshots']:
        if digest(SCHEMES / image['file']) != image['sha256']:
            raise ValueError('Changed illustration ' + image['file'])
    if models['roles'] != {role: spec['functions'] for role, spec in contract['roles'].items()}:
        raise ValueError('Role trees differ from implemented permissions')
    if models['canonical_tree'] != {'nodes': 24, 'links': 23, 'unique_parent': True, 'reachable': 24,
                                    'functions': [f['id'] for f in contract['functions']]}:
        raise ValueError('Incomplete function tree')
    if sum(proof['final_counts'].values()) != 56 or proof['calculation'] != {
            'cost_rub': '53500.00', 'price_rub': '76400.00', 'mass_kg': '7.820'}:
        raise ValueError('Unexpected persisted browser outcome')
    return contract, proof, models


