def formulas(r):
    r.paragraph('Пусть n — число позиций состава, i — номер позиции от 1 до n; qᵢ — количество компонентов, pᵢ — цена единицы в рублях, wᵢ — масса единицы в килограммах. Cкомп — стоимость компонентов; A и B — стоимость сборки и упаковки в рублях. Себестоимость C определяется выражениями:')
    equation(r,sub('C','комп'),text(' = '),summation([sub('q','i'),text(' · '),sub('p','i')]))
    equation(r,text('C = '),sub('C','комп'),text(' + A + B'))
    r.paragraph('m — доля наценки; c — доля комиссии площадки, 0 ≤ c < 1; L — логистические расходы в рублях; P₀ — цена до округления; d — положительный шаг округления в рублях; P — итоговая цена:')
    equation(r,sub('P','0'),text(' = '),fraction([text('C · (1 + m) + L')],[text('1 − c')]))
    equation(r,text('P = d · '),delimiter([fraction([sub('P','0')],[text('d')])],'⌈','⌉'))
    r.paragraph('b — масса упаковки, W — масса готового изделия с упаковкой; обе величины измеряются в килограммах:')
    equation(r,text('W = '),summation([sub('q','i'),text(' · '),sub('w','i')]),text(' + b'))
    r.paragraph('K — множество позиций, потребляющих питание, без корпуса и самого блока питания; Hᵢ — мощность единицы компонента, HБП — мощность блока питания в ваттах; β = 0,30 — доля запаса. Условие достаточности мощности:')
    equation(r,sub('H','БП'),text(' ≥ (1 + β) · '),summation([sub('q','i'),text(' · '),sub('H','i')],'i ∈ K',''))

