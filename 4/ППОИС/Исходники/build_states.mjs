const esc = value => String(value).replaceAll('&','&amp;').replaceAll('<','&lt;').replaceAll('>','&gt;');
function svg(width,height,nodes,edges,notes=[],starts=[]) {
 const text=(x,y,label,size=23)=>`<text x="${x}" y="${y}" text-anchor="middle" font-size="${size}" fill="#111">${esc(label)}</text>`;
 let body=`<svg xmlns="http://www.w3.org/2000/svg" width="${width}" height="${height}" viewBox="0 0 ${width} ${height}"><defs><marker id="arrow" markerWidth="9" markerHeight="9" refX="8" refY="4.5" orient="auto"><path d="M0 0 L8 4.5 L0 9" fill="none" stroke="#111" stroke-width="1.6"/></marker></defs><rect width="100%" height="100%" fill="white"/><g font-family="Arial">`;
 // A white under-stroke makes crossings distinct from joined transitions.
 for(const [route,id,lx,ly] of edges) body+=`<path d="${route}" stroke="white" stroke-width="7" fill="none"/><path d="${route}" stroke="#111" stroke-width="2" fill="none" marker-end="url(#arrow)"/><rect x="${lx-38}" y="${ly-23}" width="76" height="29" fill="white"/>${text(lx,ly,id,21)}`;
 for(const [x,y,route] of starts) body+=`<circle cx="${x}" cy="${y}" r="9" fill="#111"/><path d="${route}" stroke="#111" stroke-width="2" fill="none" marker-end="url(#arrow)"/>`;
 for(const [x,y,w,h,lines,composite] of nodes){
  body+=`<rect x="${x}" y="${y}" width="${w}" height="${h}" rx="15" fill="white" stroke="#111" stroke-width="2"/>`;
  if(composite) body+=`<path d="M${x} ${y+43} H${x+w}" stroke="#111" stroke-width="1.2"/>`;
  lines.forEach((line,index)=>{body+=text(x+w/2,y+(composite?(index?46+index*29:31):Math.max(30,(h-lines.length*29)/2+24)+index*29),line);});
 }
 for(const [x,y,label] of notes) body+=text(x,y,label,21);
 return body+'</g></svg>';
}
