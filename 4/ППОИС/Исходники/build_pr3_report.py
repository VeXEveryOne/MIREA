"""Submission report: the four model types and three tables required by PR3."""
import json
from report_layout import Report, SUBJECT


def build():
    data = json.loads((SUBJECT/'Схемы/ПР3_Таблицы.json').read_text(encoding='utf-8'))
    r = Report(3, 'Формирование функциональных требований к ИС Объектный анализ')
    r.heading('Формирование функциональных требований к ИС')
    r.heading('Модель анализа', 2)
    r.paragraph('Цель работы — выполнить концептуальное и динамическое моделирование информационной системы формирования и актуализации карточек компьютерных систем ООО «Юкомс».')
    r.heading('1 Диаграмма вариантов использования')
    r.paragraph('Менеджер подготавливает и публикует карточки, разработчик формирует и проверяет состав компьютерной системы, дизайнер оформляет изображения, генеральный директор проверяет и утверждает ревизию. Ozon принимает карточки и возвращает результаты публикации.')
    r.page(False,new_page=True)
    r.figure('Диаграмма вариантов использования', SUBJECT/'Схемы/01_ПР3_Варианты_ролей.png', max_height=22)
    r.page(False, new_page=True)
    r.table('Описание взаимодействий актёров и вариантов использования', ['Актёр / ВИ','Тип связи','Вариант использования'], data['links'], [4,3,9.5])
    r.page(True)
    r.heading('2 Диаграмма классов анализа')
    r.paragraph('Граничные классы (boundary) обеспечивают ввод и вывод, управляющие (control) координируют сценарии, сущности (entity) представляют предметные данные.')
    r.figure('Диаграмма классов анализа', SUBJECT/'Схемы/02_ПР3_Классы_анализа.png', max_height=11.5)
    for i, seq in enumerate(data['sequences']):
        r.page(False, new_page=True)
        r.heading('3 Диаграммы последовательности' if i == 0 else 'Утверждение ревизии карточки', 1 if i == 0 else 2)
        r.paragraph('Разработчик вводит позиции и запрашивает проверку состава. Управляющий объект получает данные версии, проверяет совместимость и сохраняет новую версию при успешной проверке. Пользователь получает номер версии либо замечания.' if i == 0 else 'Генеральный директор выбирает ревизию. Система получает её содержание и изображения, проверяет обязательные данные и при готовности устанавливает состояние READY. Результат проверки или замечания возвращаются пользователю.')
        r.figure(seq['title'], SUBJECT/f"Схемы/{'03' if i == 0 else '04'}_ПР3_Последовательность_{seq['id']}.png", max_height=18)
        r.page(False,new_page=True)
        r.table('Взаимодействие элементов диаграммы '+seq['title'].lower(), ['Отправитель','Тип сообщения','Наименование','Получатель'],seq['rows'],[4,3,5.5,4])
    r.page(True)
    r.heading('4 Диаграмма кооперации')
    r.paragraph('На диаграмме показаны объекты сценария утверждения ревизии и каналы их взаимодействия. Номера, направления и содержание сообщений соответствуют диаграмме последовательности утверждения ревизии.')
    r.figure('Кооперация объектов при утверждении ревизии карточки',SUBJECT/'Схемы/05_ПР3_Кооперация_утверждения.png',max_height=12.5)
    return r.save()


if __name__ == '__main__':
    build()
